import logging
import os
import re
from dataclasses import dataclass
from typing import Any
from uuid import uuid4

import boto3
from botocore.config import Config
from botocore.exceptions import (
    BotoCoreError,
    ClientError,
    ConnectTimeoutError,
    ConnectionClosedError,
    EndpointConnectionError,
    ReadTimeoutError,
)
from dotenv import load_dotenv

load_dotenv()

logger = logging.getLogger(__name__)
_OBJECT_KEY_PATTERN = re.compile(r"documents/[0-9a-f]{32}\Z")
_MAX_PRESIGNED_URL_TTL_SECONDS = 900
_DEFAULT_PRESIGNED_URL_TTL_SECONDS = 300


class StorageConfigurationError(RuntimeError):
    """Raised when required private object storage configuration is missing."""


class StorageServiceError(RuntimeError):
    """Raised when an object storage operation fails."""

    def __init__(self, message: str, *, retryable: bool = False) -> None:
        super().__init__(message)
        self.retryable = retryable


class ObjectMetadataMismatchError(StorageServiceError):
    """Raised when a stored object does not match the expected upload metadata."""


class ObjectNotFoundError(StorageServiceError):
    """Raised when the requested private object does not exist."""


@dataclass(frozen=True)
class S3Settings:
    region: str | None
    bucket: str | None
    endpoint_url: str | None = None
    kms_key_id: str | None = None
    presigned_url_ttl_seconds: int = _DEFAULT_PRESIGNED_URL_TTL_SECONDS

    @classmethod
    def from_env(cls) -> "S3Settings":
        ttl_text = os.getenv(
            "S3_PRESIGNED_URL_TTL_SECONDS",
            str(_DEFAULT_PRESIGNED_URL_TTL_SECONDS),
        )
        try:
            ttl = int(ttl_text)
        except ValueError as exc:
            raise StorageConfigurationError(
                "S3_PRESIGNED_URL_TTL_SECONDS must be an integer"
            ) from exc
        if not 1 <= ttl <= _MAX_PRESIGNED_URL_TTL_SECONDS:
            raise StorageConfigurationError(
                "S3_PRESIGNED_URL_TTL_SECONDS must be between 1 and 900"
            )

        return cls(
            region=os.getenv("AWS_REGION") or os.getenv("AWS_DEFAULT_REGION"),
            bucket=os.getenv("S3_BUCKET_NAME") or os.getenv("AWS_S3_BUCKET"),
            endpoint_url=os.getenv("AWS_S3_ENDPOINT_URL") or None,
            kms_key_id=os.getenv("AWS_S3_KMS_KEY_ID") or None,
            presigned_url_ttl_seconds=ttl,
        )

    def validate(self) -> None:
        if not self.region or not self.bucket:
            raise StorageConfigurationError(
                "AWS region and S3 bucket must be configured"
            )
        if not 1 <= self.presigned_url_ttl_seconds <= _MAX_PRESIGNED_URL_TTL_SECONDS:
            raise StorageConfigurationError(
                "Presigned URL expiration must be between 1 and 900 seconds"
            )


@dataclass(frozen=True)
class StoredObjectMetadata:
    content_length: int
    content_type: str | None
    etag: str | None
    checksum_sha256: str | None
    server_side_encryption: str | None
    kms_key_id: str | None


def generate_object_key() -> str:
    return f"documents/{uuid4().hex}"


class S3Storage:
    def __init__(
        self,
        settings: S3Settings | None = None,
        client: Any | None = None,
    ) -> None:
        self._settings = settings or S3Settings.from_env()
        self._client = client

    @property
    def presigned_url_ttl_seconds(self) -> int:
        return self._settings.presigned_url_ttl_seconds

    def _get_client(self):
        self._settings.validate()
        if self._client is None:
            client_options: dict[str, str] = {
                "region_name": self._settings.region,
                "endpoint_url": (
                    self._settings.endpoint_url
                    or f"https://s3.{self._settings.region}.amazonaws.com"
                ),
            }
            # Do not pass credentials: boto3's standard provider chain is used.
            self._client = boto3.client(
                "s3",
                **client_options,
                config=Config(signature_version="s3v4"),
            )
        return self._client

    def _validate_key(self, object_key: str) -> None:
        if not _OBJECT_KEY_PATTERN.fullmatch(object_key):
            raise ValueError("Object key was not generated by the storage service")

    def _upload_encryption(self) -> dict[str, str]:
        if self._settings.kms_key_id:
            return {
                "ServerSideEncryption": "aws:kms",
                "SSEKMSKeyId": self._settings.kms_key_id,
            }
        return {"ServerSideEncryption": "AES256"}

    def create_upload_url(self, content_type: str) -> dict[str, Any]:
        if not content_type or not content_type.strip():
            raise ValueError("content_type cannot be blank")
        object_key = generate_object_key()
        params = {
            "Bucket": self._settings.bucket,
            "Key": object_key,
            "ContentType": content_type,
            **self._upload_encryption(),
        }
        try:
            url = self._get_client().generate_presigned_url(
                "put_object",
                Params=params,
                ExpiresIn=self._settings.presigned_url_ttl_seconds,
            )
        except (BotoCoreError, ClientError) as exc:
            self._raise_storage_error("presign_upload", exc)
        headers = {"Content-Type": content_type}
        headers.update(
            {
                "x-amz-server-side-encryption": params["ServerSideEncryption"]
            }
        )
        if self._settings.kms_key_id:
            headers["x-amz-server-side-encryption-aws-kms-key-id"] = (
                self._settings.kms_key_id
            )
        return {"object_key": object_key, "url": url, "headers": headers}

    def create_download_url(self, object_key: str) -> str:
        self._validate_key(object_key)
        try:
            return self._get_client().generate_presigned_url(
                "get_object",
                Params={"Bucket": self._settings.bucket, "Key": object_key},
                ExpiresIn=self._settings.presigned_url_ttl_seconds,
            )
        except (BotoCoreError, ClientError) as exc:
            self._raise_storage_error("presign_download", exc)

    def get_object_metadata(self, object_key: str) -> StoredObjectMetadata:
        self._validate_key(object_key)
        try:
            response = self._get_client().head_object(
                Bucket=self._settings.bucket, Key=object_key
            )
        except ClientError as exc:
            error = exc.response.get("Error", {})
            if error.get("Code") in {"404", "NoSuchKey", "NotFound"}:
                logger.info(
                    "s3_storage_object_not_found",
                    extra={
                        "event_name": "s3_storage_object_not_found",
                        "operation": "head_object",
                    },
                )
                raise ObjectNotFoundError("Object was not found") from exc
            self._raise_storage_error("head_object", exc)
        except (BotoCoreError, ClientError) as exc:
            self._raise_storage_error("head_object", exc)
        return StoredObjectMetadata(
            content_length=response["ContentLength"],
            content_type=response.get("ContentType"),
            etag=response.get("ETag"),
            checksum_sha256=response.get("ChecksumSHA256"),
            server_side_encryption=response.get("ServerSideEncryption"),
            kms_key_id=response.get("SSEKMSKeyId"),
        )

    def verify_uploaded_object(
        self,
        object_key: str,
        expected_content_type: str,
        expected_size_bytes: int,
    ) -> StoredObjectMetadata:
        metadata = self.get_object_metadata(object_key)
        if (
            metadata.content_type != expected_content_type
            or metadata.content_length != expected_size_bytes
        ):
            raise ObjectMetadataMismatchError(
                "Uploaded object metadata does not match the expected values"
            )
        return metadata

    def delete_object(self, object_key: str) -> None:
        self._validate_key(object_key)
        try:
            self._get_client().delete_object(
                Bucket=self._settings.bucket, Key=object_key
            )
        except (BotoCoreError, ClientError) as exc:
            self._raise_storage_error("delete_object", exc)

    @staticmethod
    def _raise_storage_error(operation: str, exc: Exception) -> None:
        retryable = isinstance(
            exc,
            (
                ConnectTimeoutError,
                ConnectionClosedError,
                EndpointConnectionError,
                ReadTimeoutError,
            ),
        )
        if isinstance(exc, ClientError):
            error = exc.response.get("Error", {})
            status_code = exc.response.get("ResponseMetadata", {}).get(
                "HTTPStatusCode", 0
            )
            retryable = (
                status_code in (408, 429)
                or status_code >= 500
                or error.get("Code")
                in {
                    "InternalError",
                    "RequestTimeout",
                    "RequestTimeoutException",
                    "ServiceUnavailable",
                    "SlowDown",
                    "Throttling",
                    "ThrottlingException",
                }
            )
        logger.warning(
            "s3_storage_operation_failed",
            extra={
                "event_name": "s3_storage_operation_failed",
                "operation": operation,
                "error_type": type(exc).__name__,
            },
        )
        raise StorageServiceError(
            "Object storage operation failed", retryable=retryable
        ) from exc


s3_storage = S3Storage()
